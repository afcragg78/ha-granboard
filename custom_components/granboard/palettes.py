PALETTES: tuple[str, ...] = (DEFAULT, COLOR_1, COLORS_1_2, COLOR_GRADIENT, RAINBOW, RAINBOW_BANDS, *GRADIENTS)


def _lerp(a: RGB, b: RGB, t: float) -> RGB:
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))  # type: ignore[return-value]


def gradient(stops: Stops, pos: int) -> RGB:
    pos = int(pos) % 256
    prev = stops[0]
    for stop in stops:
        if stop[0] >= pos:
            if stop[0] == prev[0]:
                return stop[1]
            return _lerp(prev[1], stop[1], (pos - prev[0]) / (stop[0] - prev[0]))
        prev = stop
    return stops[-1][1]


def _hue(pos: int) -> RGB:
    r, g, b = colorsys.hsv_to_rgb((int(pos) % 256) / 256, 1.0, 1.0)
    return round(r * 255), round(g * 255), round(b * 255)


def color_at(name: str, pos: int, color1: RGB, color2: RGB) -> RGB:
    """Colour at 0-255 along the palette (wraps). Default and unknown names are a rainbow."""
    pos = int(pos) % 256
    if name == COLOR_1:
        return tuple(color1)  # type: ignore[return-value]
    if name == COLORS_1_2:
        return tuple(color1 if pos < 128 else color2)  # type: ignore[return-value]
    if name == COLOR_GRADIENT:
        return _lerp(tuple(color1), tuple(color2), 1 - abs(pos - 128) / 128)  # type: ignore[arg-type]
    if name == RAINBOW_BANDS:
        return _hue(pos // 32 * 32)
    stops = GRADIENTS.get(name)
    return gradient(stops, pos) if stops else _hue(pos)


def css_gradient(name: str, color1: RGB = (255, 255, 255), color2: RGB = (0, 0, 255), samples: int = 8) -> str:
    """linear-gradient() for a dashboard swatch."""
    stops = GRADIENTS.get(name)
    if stops:
        parts = [f"#{r:02x}{g:02x}{b:02x} {round(p / 255 * 100)}%" for p, (r, g, b) in stops]
    else:
        parts = []
        for i in range(samples + 1):
            r, g, b = color_at(name if name != DEFAULT else RAINBOW, round(i * 255 / samples), color1, color2)
            parts.append(f"#{r:02x}{g:02x}{b:02x} {round(i / samples * 100)}%")
    return f"linear-gradient(90deg, {', '.join(parts)})"
