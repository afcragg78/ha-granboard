def _even(*hexes: str) -> Stops:
    """Evenly spaced stops from hex strings (FastLED 16-entry palettes)."""
    n = len(hexes) - 1
    return tuple((round(i * 255 / n), (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))) for i, h in enumerate(hexes))


